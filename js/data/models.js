export const MODEL_BY_ID = Object.fromEntries(MODELS.map((m) => [m.id, m]));
export const MODELS_BY_SYSTEM = MODELS.reduce((a, m) => ((a[m.system] ||= []).push(m.id), a), {});

/** Full model objects for a system, in catalogue order. */
export function modelsFor(systemId) {
  return (MODELS_BY_SYSTEM[systemId] || []).map((id) => MODEL_BY_ID[id]).filter(Boolean);
}

/** Just the ids, for persistence and chips. */
export function modelIdsFor(systemId) {
  return [...(MODELS_BY_SYSTEM[systemId] || [])];
}

export function defaultModelFor(systemId) {
  return modelsFor(systemId)[0] || null;
}

/** Human-facing summary used by the Systems screen. */
export function modelSummary(m) {
  return `${m.year} · ${m.maker} · ${m.screen.px[0]}×${m.screen.px[1]}`;
}
