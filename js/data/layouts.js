/**
 * RetroDeck - controller layouts ("pads").
 *
 * Each pad is a list of widgets in a 100 x 46 unit space. The renderer scales
 * that space to fit the device (so the exact same layout is used on a 360px
 * phone in landscape and a 1440px tablet), and hit-testing happens in the same
 * space. Every widget that must reach the core carries an `id` that matches an
 * entry in the system's `buttons[]` array.
 *
 * Widget types
 *   dpad     { x, y, s, style:'cross'|'octo'|'disc'|'ball', dead }
 *   btn      { x, y, s, id, label, style:'round'|'oval'|'square', glyph, hold }
 *   stick    { x, y, s, id, style:'nub'|'cup'|'flat', dead, octant:false }
 *   pill     { x, y, w, h, id, angle, label }            // start / select / mode
 *   shoulder { x, y, w, h, id, label, shape:'bumper'|'trigger' }
 *   switch   { x, y, w, h, id, label, on, off }          // Atari toggles
 *   region   { x, y, w, h, id:'touch'|'fire', label }    // touchscreens / light guns
 *   keys     { x, y, w, h, rows, label }                 // mini keyboard
 */

const B = (id, x, y, s, label, style = "round", extra = {}) => ({
  t: "btn",
  id,
  x,
  y,
  s,
  label: label ?? id.toUpperCase(),
  style,
  ...extra,
});

